"""
Measured land-surface statistics from the actual pixels of a fetched scene.

Everything the report calls a percentage is computed here, from Sentinel-2
surface reflectance, using published spectral indices. Nothing on this path is
generated by a language model, and nothing is a placeholder: if the bands
needed for an index are absent the function says so and returns no number.

    NDVI  = (NIR - RED)   / (NIR + RED)        vegetation vigour
    MNDWI = (GREEN - SWIR) / (GREEN + SWIR)    open water        (Xu 2006)
    NDBI  = (SWIR - NIR)  / (SWIR + NIR)       built-up          (Zha 2003)
    BUI   = NDBI - NDVI                        built-up, vegetation-corrected

Class assignment is a decision cascade, not four independent masks, so the
percentages sum to 100 and a pixel is never counted as both water and built-up:

    water       MNDWI > 0.0
    vegetation  NDVI  >= 0.30                  (dense green cover)
    sparse veg  NDVI  in [0.18, 0.30)
    built-up    BUI   > 0.0  and NDVI < 0.18
    bare/other  everything else

The thresholds are the conventional ones from that literature. They are
scene-independent and stated in the report, so a reader can disagree with a
number by disagreeing with a threshold rather than by trusting the system.

Index ordering follows serve.aoi.S2_BANDS, which is also the order the trained
specialists consume.
"""
from __future__ import annotations

import os
from typing import Any

import numpy as np

# indices into serve.aoi.S2_BANDS
B_BLUE, B_GREEN, B_RED, B_NIR, B_SWIR16 = 1, 2, 3, 7, 10
GSD_M = 10.0                      # Sentinel-2 ground sample distance

CLASSES = ("water", "vegetation", "sparse vegetation", "built-up", "bare/other")


def _ratio(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """(a - b) / (a + b) with a zero denominator mapped to 0, not to inf."""
    num, den = a - b, a + b
    return np.divide(num, den, out=np.zeros_like(num), where=np.abs(den) > 1e-6)


def load_stack(path: str) -> np.ndarray | None:
    """The 12-band float cube written beside an AOI fetch, or None.

    `serve.aoi` writes <stem>.tif for display and <stem>.npz for the bands. A
    plain user upload has no sidecar, and RGB alone cannot produce NDVI, NDBI
    or MNDWI -- all three need NIR or SWIR. Returning None here is what makes
    the report say "not computable" instead of inventing a figure.
    """
    npz = os.path.splitext(path)[0] + ".npz"
    if not os.path.exists(npz):
        return None
    z = np.load(npz)
    if "s2" not in z:
        return None
    s2 = z["s2"].astype(np.float32)
    return s2 if s2.shape[0] >= 11 else None


def indices(s2: np.ndarray) -> dict[str, np.ndarray]:
    ndvi = _ratio(s2[B_NIR], s2[B_RED])
    mndwi = _ratio(s2[B_GREEN], s2[B_SWIR16])
    ndbi = _ratio(s2[B_SWIR16], s2[B_NIR])
    return {"ndvi": ndvi, "mndwi": mndwi, "ndbi": ndbi, "bui": ndbi - ndvi}


def classify(s2: np.ndarray) -> tuple[np.ndarray, np.ndarray, dict[str, np.ndarray]]:
    """Returns (class index per pixel, valid mask, the index rasters).

    A pixel with zero reflectance in every visible band is a fill pixel at the
    edge of a granule, not a dark surface. Counting those as "bare" would
    inflate the bare fraction of any AOI that touches a scene boundary.
    """
    ix = indices(s2)
    valid = (s2[[B_BLUE, B_GREEN, B_RED, B_NIR]].sum(0) > 0)

    cls = np.full(s2.shape[1:], CLASSES.index("bare/other"), np.int8)
    cls[ix["bui"] > 0.0] = CLASSES.index("built-up")
    cls[(ix["ndvi"] >= 0.18) & (ix["ndvi"] < 0.30)] = CLASSES.index("sparse vegetation")
    cls[ix["ndvi"] >= 0.30] = CLASSES.index("vegetation")
    cls[ix["mndwi"] > 0.0] = CLASSES.index("water")       # water wins outright
    return cls, valid, ix


def scene_stats(s2: np.ndarray) -> dict[str, Any]:
    """Per-class cover for one acquisition: percent of valid pixels and km²."""
    cls, valid, ix = classify(s2)
    n = int(valid.sum())
    if n == 0:
        return {"error": "every pixel is fill -- the AOI does not intersect "
                         "valid data in this scene"}
    px_km2 = (GSD_M ** 2) / 1e6

    cover = {}
    for i, name in enumerate(CLASSES):
        k = int(((cls == i) & valid).sum())
        cover[name] = {"pct": round(100.0 * k / n, 2),
                       "km2": round(k * px_km2, 3), "pixels": k}
    return {
        "valid_pixels": n,
        "area_km2": round(n * px_km2, 3),
        "cover": cover,
        "mean_ndvi": round(float(ix["ndvi"][valid].mean()), 4),
        "mean_mndwi": round(float(ix["mndwi"][valid].mean()), 4),
        "mean_ndbi": round(float(ix["ndbi"][valid].mean()), 4),
    }


def _delta(a: float, b: float) -> dict[str, float]:
    """Absolute change in percentage points and change relative to t1.

    Both, because they answer different questions. Built-up going 2% -> 3% of a
    scene is +1.0 pp, which sounds negligible, and +50% relative, which sounds
    dramatic. Reporting only one of them is how a true number misleads.
    """
    return {"delta_pp": round(b - a, 2),
            "relative_pct": round(100.0 * (b - a) / a, 1) if a > 1e-9 else None}


def change_stats(s2_a: np.ndarray, s2_b: np.ndarray) -> dict[str, Any]:
    """Bi-temporal comparison. `s2_a` is the earlier acquisition."""
    if s2_a.shape[1:] != s2_b.shape[1:]:
        h = min(s2_a.shape[1], s2_b.shape[1])
        w = min(s2_a.shape[2], s2_b.shape[2])
        s2_a, s2_b = s2_a[:, :h, :w], s2_b[:, :h, :w]

    ca, va, ia = classify(s2_a)
    cb, vb, ib = classify(s2_b)
    valid = va & vb
    n = int(valid.sum())
    if n == 0:
        return {"error": "the two acquisitions share no valid pixels"}
    px_km2 = (GSD_M ** 2) / 1e6

    out: dict[str, Any] = {"valid_pixels": n,
                           "area_km2": round(n * px_km2, 3),
                           "classes": {}}
    for i, name in enumerate(CLASSES):
        pa = 100.0 * int(((ca == i) & valid).sum()) / n
        pb = 100.0 * int(((cb == i) & valid).sum()) / n
